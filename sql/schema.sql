-- =========================================================
-- 13. FUNCIÓN: APROBAR MOVIMIENTO
-- =========================================================
-- Solamente ADMIN puede aprobar.
--
-- ENTRADA:
--     quantity aumenta.
--
-- SALIDA:
--     quantity disminuye.
--
-- AJUSTE:
--     quantity aumenta según la cantidad indicada.
--
-- El movimiento debe estar PENDIENTE.
--
-- El stock nunca puede quedar negativo.

CREATE OR REPLACE FUNCTION public.approve_inventory_movement(
    p_movement_id uuid
)
RETURNS public.inventory_movements
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$

DECLARE
    v_movement public.inventory_movements;
    v_inventory public.inventory;
    v_new_quantity integer;

BEGIN

    -- -----------------------------------------------------
    -- VALIDAR ADMIN
    -- -----------------------------------------------------

    IF NOT public.is_admin() THEN
        RAISE EXCEPTION
            'Solo un ADMIN puede aprobar movimientos';
    END IF;


    -- -----------------------------------------------------
    -- BLOQUEAR EL MOVIMIENTO
    -- -----------------------------------------------------

    SELECT *
    INTO v_movement
    FROM public.inventory_movements
    WHERE id = p_movement_id
    FOR UPDATE;


    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Movimiento no encontrado';
    END IF;


    -- -----------------------------------------------------
    -- SOLO SE PUEDEN APROBAR MOVIMIENTOS PENDIENTES
    -- -----------------------------------------------------

    IF v_movement.status <> 'PENDIENTE' THEN
        RAISE EXCEPTION
            'El movimiento ya fue procesado';
    END IF;


    -- -----------------------------------------------------
    -- BLOQUEAR INVENTARIO
    -- -----------------------------------------------------

    SELECT *
    INTO v_inventory
    FROM public.inventory
    WHERE id = v_movement.inventory_id
      AND item_id = v_movement.item_id
    FOR UPDATE;


    IF NOT FOUND THEN
        RAISE EXCEPTION
            'El registro de inventario no existe';
    END IF;


    -- -----------------------------------------------------
    -- CALCULAR NUEVO STOCK
    -- -----------------------------------------------------

    IF v_movement.movement_type = 'ENTRADA' THEN

        v_new_quantity :=
            v_inventory.quantity + v_movement.quantity;

    ELSIF v_movement.movement_type = 'SALIDA' THEN

        v_new_quantity :=
            v_inventory.quantity - v_movement.quantity;

    ELSIF v_movement.movement_type = 'AJUSTE' THEN

        v_new_quantity :=
            v_inventory.quantity + v_movement.quantity;

    END IF;


    -- -----------------------------------------------------
    -- EVITAR STOCK NEGATIVO
    -- -----------------------------------------------------

    IF v_new_quantity < 0 THEN
        RAISE EXCEPTION
            'Stock insuficiente para aprobar la salida';
    END IF;


    -- -----------------------------------------------------
    -- ACTUALIZAR STOCK
    -- -----------------------------------------------------

    UPDATE public.inventory
    SET
        quantity = v_new_quantity,
        updated_at = now()
    WHERE id = v_inventory.id;


    -- -----------------------------------------------------
    -- MARCAR MOVIMIENTO COMO APROBADO
    -- -----------------------------------------------------

    UPDATE public.inventory_movements
    SET
        status = 'APROBADO',
        approved_at = now()
    WHERE id = p_movement_id;


    -- -----------------------------------------------------
    -- DEVOLVER MOVIMIENTO ACTUALIZADO
    -- -----------------------------------------------------

    SELECT *
    INTO v_movement
    FROM public.inventory_movements
    WHERE id = p_movement_id;


    RETURN v_movement;

END;
$$;


-- =========================================================
-- 14. FUNCIÓN: RECHAZAR MOVIMIENTO
-- =========================================================
-- Solamente ADMIN puede rechazar.
--
-- Rechazar NO modifica inventory.quantity.

CREATE OR REPLACE FUNCTION public.reject_inventory_movement(
    p_movement_id uuid,
    p_reason text DEFAULT NULL
)
RETURNS public.inventory_movements
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$

DECLARE
    v_movement public.inventory_movements;

BEGIN

    -- -----------------------------------------------------
    -- VALIDAR ADMIN
    -- -----------------------------------------------------

    IF NOT public.is_admin() THEN
        RAISE EXCEPTION
            'Solo un ADMIN puede rechazar movimientos';
    END IF;


    -- -----------------------------------------------------
    -- RECHAZAR SOLO SI ESTÁ PENDIENTE
    -- -----------------------------------------------------

    UPDATE public.inventory_movements
    SET
        status = 'RECHAZADO',
        rejected_at = now(),
        notes = COALESCE(p_reason, notes)
    WHERE id = p_movement_id
      AND status = 'PENDIENTE'
    RETURNING *
    INTO v_movement;


    IF NOT FOUND THEN
        RAISE EXCEPTION
            'El movimiento no existe o ya fue procesado';
    END IF;


    RETURN v_movement;

END;
$$;


